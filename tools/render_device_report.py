#!/usr/bin/env python3
"""render_device_report.py — assemble the on-device report bundle.

Input:  the report directory written by tools/thor-device.sh
        (box-state.txt, steps.jsonl, run.log) plus the bench reports the
        Makefile leaves under data/ (stress_*.json, worldgen_*.json).

Output: REPORT.md on stdout — the paste-ready tables for
        docs/BENCHMARKS.md §AGX Thor and the PLACEMENT.md crossover
        section, with the box state and every step's PASS/FAIL.

The renderer is deliberately dumb: it formats what exists, it never
guesses, and anything missing renders as NOT YET MEASURED — the same rule
BENCHMARKS.md holds its own rows to.

Usage:  python3 tools/render_device_report.py data/device-report
"""

from __future__ import annotations

import json
import sys
from pathlib import Path


def load_steps(report_dir: Path) -> list[dict]:
    steps = []
    path = report_dir / "steps.jsonl"
    if path.exists():
        for line in path.read_text().splitlines():
            line = line.strip()
            if line:
                steps.append(json.loads(line))
    return steps


def load_box_state(report_dir: Path) -> dict[str, str]:
    state: dict[str, str] = {}
    path = report_dir / "box-state.txt"
    if path.exists():
        for line in path.read_text().splitlines():
            if ":" in line and not line.startswith("#"):
                key, _, value = line.partition(":")
                state[key.strip()] = value.strip()
    return state


def load_bench(data_dir: Path) -> dict[str, dict]:
    """Bench reports keyed by filename, in the Makefile's ladder order."""
    reports: dict[str, dict] = {}
    for path in sorted(data_dir.glob("*.json")):
        # Only the bench reports (the Makefile's names), not the report
        # bundle itself, which lives in a subdirectory.
        if path.parent.name == "device-report":
            continue
        try:
            report = json.loads(path.read_text())
        except json.JSONDecodeError:
            continue
        reports[path.name] = report
    return reports


def ns_to_us(ns: int) -> str:
    return f"{ns / 1000:.1f} µs" if ns < 1_000_000 else f"{ns / 1_000_000:.2f} ms"


def fmt_row(profile: str, population: str, r: dict) -> str:
    plain = r.get("plain_ns", {})
    auction = r.get("auction_ns", {})
    sweep = r.get("sweep_ns", {})
    return (
        f"| {profile} | {population} "
        f"| {ns_to_us(plain.get('p50', 0))} | {ns_to_us(auction.get('p50', 0))} "
        f"| {ns_to_us(sweep.get('p50', 0))} "
        f"| {ns_to_us(auction.get('p95', 0))} | {r.get('chain_hash', '?')} |"
    )


POPULATIONS = {
    "stress_10k.json": ("stress", "10,000"),
    "stress_50k.json": ("stress", "50,000"),
    "stress_100k.json": ("stress", "100,000"),
    "worldgen_50k.json": ("world-gen", "~3,200 live (50k capacity)"),
}


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 64
    report_dir = Path(sys.argv[1])
    data_dir = report_dir.parent
    steps = load_steps(report_dir)
    box = load_box_state(report_dir)
    reports = load_bench(data_dir)
    out: list[str] = []
    add = out.append

    add("# ecology-thor — on-device report")
    add("")
    add(f"*Generated by `tools/thor-device.sh` on `{box.get('host', 'unknown')}`, "
        f"{box.get('uname', 'unknown')}.*")
    add("")
    add("## Box state")
    add("")
    add("| | |")
    add("|---|---|")
    for key in ("model", "kernel", "MemTotal", "MemAvailable", "nvcc", "cargo", "rustc"):
        if key in box:
            add(f"| {key} | {box[key]} |")
    for key, value in box.items():
        if key.startswith("nvpmodel") or "power" in key.lower():
            add(f"| {key} | {value} |")
    add("")
    add("*The project's working figure for this pool: 122 GiB usable "
        "(THOR.md). The 25 GiB floor and `~/lm-wt/heavy.lock` were held "
        "for every heavy step.*")
    add("")

    add("## Steps")
    add("")
    add("| # | step | status | seconds | detail |")
    add("|---|---|---|---|---|")
    for i, step in enumerate(steps, 1):
        add(f"| {i} | {step.get('step', '?')} | **{step.get('status', '?')}** "
            f"| {step.get('seconds', 0):.0f} | {step.get('detail', '')} |")
    add("")
    add("*The `guard` step running on-device is also the aarch64 leg of the "
        "golden determinism contract (`tests/golden.rs`): the chain hash "
        "must equal the committed `37a37a2c4ec5a9a9` on this platform "
        "too — a FAIL there is a determinism bug, not a flaky test.*")
    add("")

    add("## Paste into `docs/BENCHMARKS.md` §AGX Thor")
    add("")
    add("*(Keep the sandbox table above it; this is the second table. "
    "Annotate the context line: clocks pinned? power mode? thermal state.)*")
    add("")
    add("| Profile | Population | plain p50 | auction p50 | sweep p50 | auction p95 | chain hash |")
    add("|---|---|---|---|---|---|---|")
    # Rows in the Makefile's ladder order, not alphabetical.
    ladder = [name for name in POPULATIONS if name in reports]
    ladder += [name for name in reports if name not in POPULATIONS]
    for name in ladder:
        report = reports[name]
        if name in POPULATIONS:
            profile, population = POPULATIONS[name]
        else:
            profile, population = report.get("profile", "?"), "?"
        add(fmt_row(profile, population, report))
    if not reports:
        add("| (no bench reports found — run without `--skip-bench`) | | | | | | |")
    add("")
    add("**Device sweep column (per-kernel device timings):** NOT YET "
        "MEASURED — the parity gate proves bit-exactness, it does not time "
        "the kernels. A `--device-bench` mode (mirror → sweep → readback, "
        "timed, at 10k/100k/1M) is the follow-up; until it exists the "
        "PLACEMENT.md crossovers stay thresholds, not measurements.")
    add("")

    add("## Paste into `docs/PLACEMENT.md` (the measured-crossover section)")
    add("")
    add("*The one number that decides CPU-vs-GPU placement is the sweep "
    "frame cost at each population, CPU (from the table above) against "
    "launch+kernel time on device. Until the device-bench mode exists, "
    "record the CPU ladder here and leave the crossover column open.*")
    add("")
    add("| Population | CPU sweep p50 (this run) | device sweep p50 | crossover reached? |")
    add("|---|---|---|---|")
    for name in [n for n in POPULATIONS if n in reports]:
        population = POPULATIONS[name][1]
        add(f"| {population} | {ns_to_us(reports[name].get('sweep_ns', {}).get('p50', 0))} "
            f"| NOT YET MEASURED | — |")
    add("")

    add("## Parity evidence")
    add("")
    parity = next((s for s in steps if s.get("step") == "parity"), None)
    if parity:
        add(f"* {parity.get('detail', '')}")
        add("* Full log: `parity.log` beside this file. The gate asserts "
            "every f32 column bit-for-bit (`.to_bits()` equality) between "
            "the sm_110 kernels and the CPU reference — the precondition "
            "for the v0.2 device-authoritative sweeps (PLACEMENT.md).")
    else:
        add("* Parity did not run — see the steps table.")
    add("")

    add("## PTX evidence (register pressure, sm_110)")
    add("")
    add("```")
    ptx_log = report_dir / "ptx-check.log"
    if ptx_log.exists():
        for line in ptx_log.read_text().splitlines():
            if "register" in line.lower() or "spill" in line.lower() or "ptx-check" in line:
                add(line)
    else:
        add("(ptx-check did not run)")
    add("```")
    add("")

    passed = sum(1 for s in steps if s.get("status") == "PASS")
    failed = sum(1 for s in steps if s.get("status") == "FAIL")
    skipped = sum(1 for s in steps if s.get("status") == "SKIP")
    add("---")
    add("")
    add(f"**Summary: {passed} passed, {failed} failed, {skipped} skipped.**")
    add("")
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
